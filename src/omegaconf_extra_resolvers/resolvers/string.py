def oc_upper(s: str) -> str:
    """Return ``s`` converted to upper-case.

    Parameters
    ----------
    s : str
        Input string.

    Returns
    -------
    str
        Upper-cased version of ``s``.
    """
    return s.upper()


def oc_lower(s: str) -> str:
    """Return ``s`` converted to lower-case.

    Parameters
    ----------
    s : str
        Input string.

    Returns
    -------
    str
        Lower-cased version of ``s``.
    """
    return s.lower()
